"""Extract reviewed simulation cells; never execute notebook setup or LLM cells."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parent
DESTINATION = ROOT / 'src' / 'upstream_env.py'


def render_source() -> str:
    """Apply explicit, checked local adaptations to the pinned upstream source."""
    notebook = ROOT / 'code_as_policies' / 'Interactive_Demo.ipynb'
    manifest = json.loads((ROOT / 'upstream.json').read_text(encoding='utf-8'))
    expected = next(item['sha256'] for item in manifest['files'] if item['file'] == notebook.name)
    data = notebook.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('Upstream notebook checksum mismatch; do not regenerate from an unreviewed source.')
    cells = json.loads(data)['cells']
    header = '''# Copyright 2022 Google LLC. SPDX-License-Identifier: Apache-2.0
# Derived from the official Interactive_Demo.ipynb, code cells 7, 8, 9 (zero based).
# See code_as_policies/LICENSE and upstream.json.
# Generated by build_env.py; make local adaptations there, then regenerate.
# Local changes: remove unused gripper thread/check_grasp; instance-local camera;
# CPU renderer; relative data path for Windows Unicode directories.
# LocalEnv in run_offline.py synchronizes mimic joints before physics steps.
# The original Notebook is unchanged.
import os
import numpy as np
import pybullet
import pybullet_data

'''
    source = '\n\n'.join(''.join(cells[i]['source']) for i in (7, 8, 9))
    replacements = {
        '    self.n_joints = pybullet.getNumJoints(self.body)\n': '',
        '''    # Start thread to handle additional gripper constraints.
    self.motor_joint = 1
    self.constraints_thread = threading.Thread(target=self.step)
    self.constraints_thread.daemon = True
    self.constraints_thread.start()
''': '''    # Mimic joints are updated synchronously by LocalEnv.
    self.motor_joint = 1
''',
        '''  # Control joint positions by enforcing hard contraints on gripper behavior.
  # Set one joint as the open/close motor joint (other joints should mimic).
  def step(self):
    while True:
      try:
        currj = [pybullet.getJointState(self.body, i)[0] for i in range(self.n_joints)]
        indj = [6, 3, 8, 5, 10]
        targj = [currj[1], -currj[1], -currj[1], currj[1], currj[1]]
        pybullet.setJointMotorControlArray(self.body, indj, pybullet.POSITION_CONTROL, targj, positionGains=np.ones(5))
      except:
        return
      sleep(0.001)

''': '',
        '''  def check_grasp(self):
    while self.moving():
      sleep(0.001)
    success = self.grasp_width() > 0.01
    return success

''': '',
        '''    if self.gripper is not None:
      while self.gripper.constraints_thread.is_alive():
        self.constraints_thread_active = False
''': '',
        'color, _, _, _, _ = env.render_image(image_size, intrinsics)': 'color, _, _, _, _ = self.render_image(image_size, intrinsics)',
        'renderer=pybullet.ER_BULLET_HARDWARE_OPENGL': 'renderer=pybullet.ER_TINY_RENDERER',
        'pybullet.setAdditionalSearchPath(pybullet_data.getDataPath())': 'pybullet.setAdditionalSearchPath(os.path.relpath(pybullet_data.getDataPath()))',
    }
    for old, new in replacements.items():
        if source.count(old) != 1:
            raise ValueError(f'Upstream changed; expected exactly one occurrence of: {old!r}')
        source = source.replace(old, new)
    return header + '\n'.join(line.rstrip() for line in source.splitlines()) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check the generated file without changing it.')
    args = parser.parse_args()
    source = render_source()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text(encoding='utf-8') != source:
            print('src/upstream_env.py is out of date. Run build_env.py to regenerate it.')
            return 1
        print('Generated environment matches the pinned notebook and local adaptations.')
        return 0
    DESTINATION.parent.mkdir(exist_ok=True)
    DESTINATION.write_text(source, encoding='utf-8', newline='\n')
    print('Extracted src/upstream_env.py; original notebook unchanged.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
